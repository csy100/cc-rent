import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement>;

function base(props: IconProps) {
  return {
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 1.5,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    ...props,
  };
}

/** 星芒标记（Claude 风格八芒星），由程序计算顶点，fill 模式 */
export function Sparkle({ className, style, ...props }: IconProps) {
  const cx = 12;
  const cy = 12;
  const rays = 8;
  const long = 10.8;
  const short = 5.6;
  let d = "";
  for (let i = 0; i < rays; i++) {
    const angle = (i * Math.PI) / rays - Math.PI / 2;
    const r = i % 2 === 0 ? long : short;
    const x = cx + r * Math.cos(angle);
    const y = cy + r * Math.sin(angle);
    d += `${i === 0 ? "M" : "L"}${x.toFixed(2)} ${y.toFixed(2)}`;
  }
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden
      className={className}
      style={style}
      {...props}
    >
      <path d={d + "Z"} stroke="currentColor" strokeWidth={1} strokeLinejoin="round" />
    </svg>
  );
}

